export function getProblem(id: string): Problem | undefined {
  return PROBLEMS.find((p) => p.id === id);
}

export function problemsForTopic(topicId: string): Problem[] {
  return PROBLEMS.filter((p) => p.topicId === topicId);
}

/** Дараагийн бодлого. Дуусвал null — session нь тодорхой төгсгөлтэй. */
export function nextProblem(currentId: string): Problem | null {
  const i = PROBLEMS.findIndex((p) => p.id === currentId);
  return i >= 0 && i + 1 < PROBLEMS.length ? PROBLEMS[i + 1] : null;
}
